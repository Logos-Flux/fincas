#!/usr/bin/env python3
"""Build the ERP back-office theme stylesheets from small palette specs.

A theme is a PALETTE below: page/surface/card colours, text, accent, status
colours, a font pair and a corner radius. This script expands each one into
the full --brand-t-* token set that golden_erp/static/assets/css/tabler-bindings.css maps
onto Tabler (both colour modes):

  * the colours themselves, plus "-rgb" triplets (Tabler builds rgba() from them)
  * --brand-t-on-<fill>: black or white, whichever reads best on that fill
  * --brand-t-accent-ink: the accent, adjusted until it reads as text (AA)
  * --brand-t-gray-50…950: a neutral ramp tinted to the theme, which Tabler
    uses for every surface and border it doesn't name explicitly

and **refuses to write a theme that fails WCAG AA** for any text/background
pair it defines. Output goes between marker comments in
golden_erp/static/assets/css/themes/<name>.css, so hand-written "flourish" rules below
the block (EVA-01's circuit board, say) survive a rebuild.

Run from the repo root:  python3 scripts/build_erp_themes.py
Then register new names in settings.ERP_THEMES (name, label, css, mode, bg).
"""

