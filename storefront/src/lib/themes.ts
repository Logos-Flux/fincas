export function themeName(id: string): string {
  return ALL_THEMES.find((t) => t.id === id)?.name ?? id;
}

/** Resolve a stored id (possibly pre-rename) to a current theme id. */
export function resolveThemeId(id: string | null): string {
  if (!id) return DEFAULT_THEME_ID;
  const mapped = LEGACY_THEME_IDS[id] ?? id;
  return ALL_THEME_IDS.includes(mapped) ? mapped : DEFAULT_THEME_ID;
}
