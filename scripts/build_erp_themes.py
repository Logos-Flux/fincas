def rgb(h: str) -> tuple[int, int, int]:
    h = h.lstrip("#")
    return tuple(int(h[i : i + 2], 16) for i in (0, 2, 4))  # type: ignore[return-value]


def hexify(c) -> str:
    return "#" + "".join(f"{round(max(0, min(255, x))):02x}" for x in c)


def lum(c) -> float:
    def ch(x):
        x /= 255
        return x / 12.92 if x <= 0.04045 else ((x + 0.055) / 1.055) ** 2.4

    r, g, b = (ch(x) for x in c)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a, b) -> float:
    la, lb = sorted((lum(a), lum(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def mix(a, b, t):
    return tuple(a[i] + (b[i] - a[i]) * t for i in range(3))


BLACK, WHITE = (0, 0, 0), (255, 255, 255)


def on(fill):
    return WHITE if contrast(fill, WHITE) >= contrast(fill, BLACK) else BLACK


def build(name: str, p: dict) -> str:
    c = {k: rgb(v) for k, v in p.items() if isinstance(v, str) and v.startswith("#")}
    bgs = {k: c[k] for k in ("deep", "surface", "card", "hover")}
    errors = []

    def need(fg_key, fg, where=bgs, ratio=AA):
        for bk, bg in where.items():
            r = contrast(fg, bg)
            if r < ratio:
                errors.append(f"{fg_key} on {bk} = {r:.2f}:1")

    for k in ("text", "bright", "muted", "success", "warning", "error", "info"):
        need(k, c[k])

    # Accent as text: nudge toward the bright end until it reads everywhere.
    toward = c["bright"]
    ink, t = c["accent"], 0.0
    while min(contrast(ink, bg) for bg in bgs.values()) < AA and t < 1:
        t = round(t + 0.02, 2)
        ink = mix(c["accent"], toward, t)
    need("accent-ink", ink)

    fills = {k: c[k] for k in ("accent", "accent_alt", "success", "warning", "error", "info")}
    for k, fill in fills.items():
        r = contrast(on(fill), fill)
        if r < AA:
            errors.append(f"text on {k} fill = {r:.2f}:1")

    if errors:
        raise SystemExit(f"{name}: fails WCAG AA — " + "; ".join(errors))

    # Neutral ramp, lightest → darkest, tinted by the theme's own ends.
    light_end, dark_end = (c["deep"], c["bright"]) if p["mode"] == "light" else (c["bright"], c["deep"])
    # Spacing copied from Tabler's own grays (#f9fafb … #111827): weighted
    # dark in the middle, so gray-500 — which Tabler uses for text such as
    # inactive tabs — still passes AA. An even ramp left it at ~3.6:1.
    stops = {50: 0.025, 100: 0.05, 200: 0.11, 300: 0.19, 400: 0.42, 500: 0.62,
             600: 0.76, 700: 0.84, 800: 0.93, 900: 0.97, 950: 1.0}  # fmt: skip

    gray500 = mix(light_end, dark_end, stops[500])
    surface_bgs = {k: c[k] for k in ("surface", "card")}
    if p["mode"] == "light":
        need("gray-500", gray500, surface_bgs)
    if errors:
        raise SystemExit(f"{name}: fails WCAG AA — " + "; ".join(errors))

    font_import, font_stack = FONTS[p["font"]]
    out = [BEGIN, f'@import url("https://fonts.googleapis.com/css2?family={font_import}&display=swap");', ":root {"]
    names = {"accent_alt": "accent-alt", "error": "error"}
    for k in ("deep", "surface", "card", "hover", "text", "bright", "muted", "border",
              "accent", "accent_alt", "success", "warning", "error", "info"):  # fmt: skip
        n = names.get(k, k)
        out.append(f"  --brand-t-{n}: {p[k]};")
        out.append(f"  --brand-t-{n}-rgb: {', '.join(str(x) for x in c[k])};")
    for k, fill in fills.items():
        out.append(f"  --brand-t-on-{names.get(k, k)}: {hexify(on(fill))};")
    out.append(f"  --brand-t-accent-ink: {hexify(ink)};")
    out.append(f"  --brand-t-accent-ink-rgb: {', '.join(str(round(x)) for x in ink)};")
    for s, t in stops.items():
        g = mix(light_end, dark_end, t)
        out.append(f"  --brand-t-gray-{s}: {hexify(g)};")
    a = c["accent"]
    out += [
        f"  --brand-t-accent-glow: rgba({a[0]}, {a[1]}, {a[2]}, 0.18);",
        f"  --brand-t-border-active: rgba({a[0]}, {a[1]}, {a[2]}, 0.45);",
        f"  --brand-t-radius: {p['radius']};",
        f"  --font-primary: {font_stack};",
        f"  --font-display: {font_stack};",
        f"  --font-mono: {MONO};",
        "}",
        END,
    ]
    return "\n".join(out) + "\n"


def main() -> None:
    for name, p in PALETTES.items():
        block = build(name, p)
        path = THEMES / f"{name}.css"
        css = path.read_text() if path.exists() else ""
        if BEGIN in css:
            css = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n", lambda _: block, css, flags=re.S)
        else:
            css = block + ("\n" + css if css else "")
        path.write_text(css)
        print(f"{name:10} {p['mode']:5} ok")


if __name__ == "__main__":
    sys.exit(main())
