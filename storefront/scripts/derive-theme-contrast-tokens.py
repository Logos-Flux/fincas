#!/usr/bin/env python3
"""Derive the two contrast tokens every theme skin needs, and write them in.

  --color-t-on-accent   text on an accent fill: black or white, whichever
                        contrasts more with --color-t-accent.
  --color-t-accent-ink  accent-coloured text: the accent itself when it already
                        reads at WCAG AA (4.5:1) on the theme's deep, surface
                        and card backgrounds, otherwise the accent nudged toward
                        white (dark themes) or black (light themes) until it does.

Run from storefront/:  python3 scripts/derive-theme-contrast-tokens.py
Re-run after adding a theme or changing an accent; it rewrites its own block.
"""

import pathlib
import re
import sys

THEMES = pathlib.Path(__file__).resolve().parent.parent / "public" / "themes"
BEGIN = "  /* contrast tokens: generated by scripts/derive-theme-contrast-tokens.py */"
END = "  /* end contrast tokens */"
AA = 4.5


def parse(value):
    v = value.strip().lower()
    m = re.fullmatch(r"#([0-9a-f]{3}|[0-9a-f]{6})", v)
    if m:
        h = m.group(1)
        if len(h) == 3:
            h = "".join(c * 2 for c in h)
        return tuple(int(h[i : i + 2], 16) for i in (0, 2, 4)) + (1.0,)
    m = re.fullmatch(r"rgba?\(\s*([\d.]+)[\s,]+([\d.]+)[\s,]+([\d.]+)(?:[\s,/]+([\d.]+%?))?\s*\)", v)
    if m:
        a = m.group(4)
        alpha = 1.0 if a is None else (float(a[:-1]) / 100 if a.endswith("%") else float(a))
        return (float(m.group(1)), float(m.group(2)), float(m.group(3)), alpha)
    if v == "transparent":
        return (0.0, 0.0, 0.0, 0.0)
    return None


def over(fg, bg):
    a = fg[3]
    return tuple(fg[i] * a + bg[i] * (1 - a) for i in range(3)) + (1.0,)


def luminance(c):
    def ch(x):
        x /= 255
        return x / 12.92 if x <= 0.04045 else ((x + 0.055) / 1.055) ** 2.4

    r, g, b = (ch(x) for x in c[:3])
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a, b):
    la, lb = sorted((luminance(a), luminance(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def mix(a, b, t):
    return tuple(a[i] + (b[i] - a[i]) * t for i in range(3)) + (1.0,)


def hexify(c):
    return "#" + "".join(f"{round(x):02x}" for x in c[:3])


def root_vars(css):
    block = re.search(r":root\s*\{(.*?)\n\}", css, re.S)
    out = {}
    for name, value in re.findall(r"(--color-t-[\w-]+)\s*:\s*([^;]+);", block.group(1) if block else ""):
        out.setdefault(name, value.split("/*")[0].strip())
    return out


def derive(css):
    v = root_vars(css)
    accent, deep = parse(v.get("--color-t-accent", "")), parse(v.get("--color-t-deep", ""))
    if not accent or not deep:
        return None
    accent = over(accent, deep)
    bgs = [deep] + [over(c, deep) for c in (parse(v.get(k, "")) for k in ("--color-t-surface", "--color-t-card")) if c]

    black, white = (0, 0, 0, 1.0), (255, 255, 255, 1.0)
    on_accent = white if contrast(accent, white) >= contrast(accent, black) else black

    toward = white if luminance(deep) < 0.18 else black
    ink, t = accent, 0.0
    while min(contrast(ink, bg) for bg in bgs) < AA and t < 1:
        t = round(t + 0.02, 2)
        ink = mix(accent, toward, t)
    return hexify(on_accent), hexify(ink), contrast(accent, on_accent)


def main():
    weak = []
    for path in sorted(THEMES.glob("*.css")):
        css = path.read_text()
        css = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n", "", css, flags=re.S)
        got = derive(css)
        if not got:
            print(f"skip {path.name}: no parsable accent/deep", file=sys.stderr)
            continue
        on_accent, ink, ratio = got
        lines = [BEGIN, f"  --color-t-on-accent: {on_accent};"]
        # A theme that defines its own accent-ink keeps it.
        if "--color-t-accent-ink" not in root_vars(css):
            lines.append(f"  --color-t-accent-ink: {ink};")
        lines.append(END)
        css = re.sub(r"(:root\s*\{\n)", lambda m: m.group(1) + "\n".join(lines) + "\n", css, count=1)
        path.write_text(css)
        if ratio < AA:
            weak.append(f"{path.stem} ({ratio:.2f}:1)")
    if weak:
        print("accent fills where neither black nor white reaches 4.5:1 (large text only):")
        print("  " + ", ".join(weak))


if __name__ == "__main__":
    main()
