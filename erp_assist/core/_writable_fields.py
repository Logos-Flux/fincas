# ---- Validation helper -----------------------------------------------------


def validate_fields(
    fields: dict,
    allowed: frozenset[str],
    resource_name: str,
) -> None:
    """Raise ERPValidationError if any key in `fields` isn't in `allowed`.

    The LLM will see the unknown keys and can correct them on the next turn.
    If the set is wrong (e.g. Django added a new field), update this file —
    much better than silently dropping writes at the DRF boundary.
    """
    unknown = set(fields) - allowed
    if unknown:
        raise ERPValidationError(
            f"Unknown {resource_name} field(s): {sorted(unknown)}. "
            f"Allowed fields: {sorted(allowed)}",
            details={"unknown_fields": sorted(unknown)},
        )
