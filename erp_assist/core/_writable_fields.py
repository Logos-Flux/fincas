"""Allow-lists of writable fields per DRF resource.

These exist so that `update_*` calls fail loudly on typos instead of
silently succeeding at the DRF boundary (DRF will happily accept-and-ignore
unknown keys by default). If Django adds a field and this file hasn't been
updated yet, the caller gets a helpful error pointing at the unknown key —
much better than the update silently doing nothing.

Keep these sorted alphabetically so diffs are easy to review. Each set
should match the corresponding serializer's writable fields (everything
not in `read_only_fields`).

Two deliberate exclusions, enforced at the DRF boundary as well:

- ``status`` — never PATCHable on orders/quotes/sub-orders/POs. Legal
  moves go through the guarded ``POST .../transition/`` action (the
  model's ``VALID_TRANSITIONS`` map is the single source of truth).
- Server-computed totals (``grand_total``, ``subtotal*``, ``tax_total``,
  ``balance_due``, ``amount_paid``) — computed by ``recalculate_totals()``
  / the payment ledger. Call the ``POST .../recalculate/`` action after
  editing line items instead of writing totals directly.

The ``update_*`` helpers below route ``status`` to the transition
endpoint automatically, so callers keep passing ``{"status": ...}``.
"""

